#!/usr/bin/env bash

# Generate the model/effort benchmark design: bench/design.tsv, bench/arms
# and nix/ab-arms.nix, all from one construction so they cannot drift apart.
#
#   bench/design.sh [--root DIR]           write the three files under DIR
#   bench/design.sh [--root DIR] --check   exit non-zero if DIR's copies differ
#
# DIR defaults to the repo root. Factor codes, with c s w r b the coordinator,
# scout, worker and reviewer model levels and a two-level block:
#
#   models  o=claude-opus-5-5 s=claude-sonnet-5-5 h=claude-haiku-5-5
#   efforts l=low m=medium h=high x=xhigh
#   c in {o,s}  s in {o,s,h}  w in {o,s,h}  r in {o,s}  b in {0,1}  (72 rows)
#   k  = 4c + 2r + b
#   CE = (s + w + k) mod 3   -> {m,h,x}   coordinator effort
#   WE = (s + 2w + 2k) mod 3 -> {l,m,h}   worker effort
#   RE = (s + w + 2k) mod 3  -> {m,h,x}   reviewer effort
#   SE = (b + c + r) mod 2   -> {l,m}     scout effort
#
# Each model cell (c,s,w,r) appears twice with every effort differing, and
# each effort is balanced against every model factor and every other effort
# except CE x RE, which stays within 1.5x. tests/bench-design.bats asserts
# all of it. The scout, worker and reviewer are image-time (#5254), so they
# name the image; the coordinator is a dispatch-time --model/--effort flag.

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
check=0
while [ $# -gt 0 ]; do
  case "$1" in
    --root) root="${2:?--root needs a directory}"; shift 2 ;;
    --check) check=1; shift ;;
    *) printf '!! unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done

files=(bench/design.tsv bench/arms nix/ab-arms.nix)

generate() {
  local out=$1
  mkdir -p "$out/bench" "$out/nix"
  awk '
    function mid(code) { return code == "o" ? "claude-opus-5-5" : code == "s" ? "claude-sonnet-5-5" : "claude-haiku-5-5" }
    function eword(code) { return code == "l" ? "low" : code == "m" ? "medium" : code == "h" ? "high" : "xhigh" }
    BEGIN {
      split("o s", CM, " "); split("o s h", SM, " "); split("o s h", WM, " "); split("o s", RM, " ")
      split("m h x", CEL, " "); split("l m h", WEL, " "); split("m h x", REL, " "); split("l m", SEL, " ")
      OFS = "\t"
      print "arm", "coord_model", "coord_effort", "scout_model", "scout_effort", "worker_model", "worker_effort", "reviewer_model", "reviewer_effort", "image"
      for (c = 0; c < 2; c++) for (s = 0; s < 3; s++) for (w = 0; w < 3; w++)
      for (r = 0; r < 2; r++) for (b = 0; b < 2; b++) {
        k = 4 * c + 2 * r + b
        ce = CEL[(s + w + k) % 3 + 1]
        we = WEL[(s + 2 * w + 2 * k) % 3 + 1]
        re = REL[(s + w + 2 * k) % 3 + 1]
        se = SEL[(b + c + r) % 2 + 1]
        img = "s" SM[s + 1] se "-w" WM[w + 1] we "-r" RM[r + 1] re
        print "c" CM[c + 1] ce "-" img, mid(CM[c + 1]), eword(ce), mid(SM[s + 1]), eword(se), \
          mid(WM[w + 1]), eword(we), mid(RM[r + 1]), eword(re), img
      }
    }' >"$out/bench/design.tsv"

  {
    cat <<'EOF'
# bench.sh arms: <name> <flake app> [dispatch flags...]
# Generated by bench/design.sh from bench/design.tsv; do not hand-edit. Each
# arm is c<M><E>-s<M><E>-w<M><E>-r<M><E> (coordinator, scout, worker,
# reviewer; models o/s/h = opus/sonnet/haiku, efforts l/m/h/x =
# low/medium/high/xhigh). Scout, worker and reviewer are image-time, so they
# pick the `.#ab-<image>` app from nix/ab-arms.nix; the coordinator is the
# dispatch-time --model/--effort. The first arm is the summary's delta
# baseline. Renaming an arm starts a fresh series; changing its spec under the
# same name gets flagged in the summary.
EOF
    tail -n +2 "$out/bench/design.tsv" | awk -F'\t' '{ print $1, ".#ab-" $10, "--model", $2, "--effort", $3 }'
  } >"$out/bench/arms"

  {
    cat <<'EOF'
# bench.sh's image-time arms, generated by bench/design.sh from
# bench/design.tsv; do not hand-edit, rerun the script. Each name becomes
# `.#ab-<name>`: the dogfood Harness with the scout, worker and reviewer
# models and efforts changed (#5254). review-axis is set to the reviewer's
# values explicitly, since mkAbArmRoster patches already-resolved entries and
# would leave it on the dogfood reviewer. The coordinator's --model/--effort
# are dispatch-time, so they live in bench/arms.
{
EOF
    tail -n +2 "$out/bench/design.tsv" | awk -F'\t' '
      seen[$10]++ { next }
      {
        printf "  \"%s\" = {\n", $10
        printf "    models = {\n      scout = \"%s\";\n      worker = \"%s\";\n      reviewer = \"%s\";\n      \"review-axis\" = \"%s\";\n    };\n", $4, $6, $8, $8
        printf "    efforts = {\n      scout = \"%s\";\n      worker = \"%s\";\n      reviewer = \"%s\";\n      \"review-axis\" = \"%s\";\n    };\n", $5, $7, $9, $9
        printf "  };\n"
      }'
    echo "}"
  } >"$out/nix/ab-arms.nix"
}

if [ "$check" -eq 0 ]; then
  generate "$root"
  exit 0
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
generate "$tmp"
drift=0
for f in "${files[@]}"; do
  if [ ! -f "$root/$f" ]; then
    printf '!! %s: missing\n' "$f" >&2
    drift=1
  elif ! d=$(diff -u "$root/$f" "$tmp/$f"); then
    printf '!! %s: differs from bench/design.sh output (%s lines changed)\n' \
      "$f" "$(grep -c '^[-+][^-+]' <<<"$d")" >&2
    head -n 20 <<<"$d" >&2
    drift=1
  fi
done
if [ "$drift" -ne 0 ]; then
  printf '!! rerun bench/design.sh to regenerate\n' >&2
  exit 1
fi
