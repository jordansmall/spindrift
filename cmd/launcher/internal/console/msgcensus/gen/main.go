// Command gen regenerates msg_census_gen.go in the console package from the
// types carrying the isConsoleMsg marker method. Run it as `go generate
// ./cmd/launcher/internal/console`; the //go:generate directive is in msg.go.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"spindrift.dev/launcher/internal/console/msgcensus"
)

const header = `// Code generated by msgcensus/gen from this package's Go declarations. DO NOT EDIT.
package console

// msgCensus is the sorted list of every type in this package implementing
// Msg (carrying the isConsoleMsg marker method). It is regenerated by
// running ` + "`go generate ./cmd/launcher/internal/console`" + ` after adding or
// removing a Msg type.
var msgCensus = []string{
`

// Tests override writeFile to capture the generated output without touching disk.
var writeFile = os.WriteFile

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "msgcensus/gen:", err)
		os.Exit(1)
	}
}

func run() error {
	consoleDir, err := resolveConsoleDir()
	if err != nil {
		return err
	}

	formatted, err := generate(consoleDir)
	if err != nil {
		return err
	}

	outPath := filepath.Join(consoleDir, "msg_census_gen.go")
	if err := writeFile(outPath, formatted, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", outPath, err)
	}

	return nil
}

func resolveConsoleDir() (string, error) {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		// runtime.Caller(0) never fails in practice, so this branch is untestable.
		return "", fmt.Errorf("could not determine caller file location")
	}

	// thisFile is .../internal/console/msgcensus/gen/main.go, so three Dir calls
	// strip main.go, gen, and msgcensus to reach the console directory.
	return filepath.Dir(filepath.Dir(filepath.Dir(thisFile))), nil
}

func generate(dir string) ([]byte, error) {
	names, err := msgcensus.Collect(dir)
	if err != nil {
		return nil, fmt.Errorf("collecting Msg census: %w", err)
	}

	var b strings.Builder
	b.WriteString(header)
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q,\n", name)
	}
	b.WriteString("}\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}

	return formatted, nil
}
