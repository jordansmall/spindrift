// Command gen regenerates msg_census_gen.go in the console package by
// AST-walking the package's msg_*.go declarations for every type carrying
// the isConsoleMsg marker method. Invoke it via `go generate
// ./cmd/launcher/internal/console` (the //go:generate directive lives in
// msg.go) rather than running it directly.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"spindrift.dev/launcher/internal/console/msgcensus"
)

const header = `// Code generated by msgcensus/gen from this package's msg_*.go declarations. DO NOT EDIT.
package console

// msgCensus is the sorted list of every type in this package implementing
// Msg (carrying the isConsoleMsg marker method). It is regenerated by
// running ` + "`go generate ./cmd/launcher/internal/console`" + ` after adding or
// removing a Msg type.
var msgCensus = []string{
`

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "msgcensus/gen:", err)
		os.Exit(1)
	}
}

func run() error {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		return fmt.Errorf("could not determine caller file location")
	}

	// thisFile is .../internal/console/msgcensus/gen/main.go; the console
	// package directory is two levels up.
	consoleDir := filepath.Dir(filepath.Dir(filepath.Dir(thisFile)))

	names, err := msgcensus.Collect(consoleDir)
	if err != nil {
		return fmt.Errorf("collecting Msg census: %w", err)
	}

	var b strings.Builder
	b.WriteString(header)
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q,\n", name)
	}
	b.WriteString("}\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("formatting generated source: %w", err)
	}

	outPath := filepath.Join(consoleDir, "msg_census_gen.go")
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", outPath, err)
	}

	return nil
}
