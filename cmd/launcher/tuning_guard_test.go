const (
	tuningPkgDir   = "internal/tuning/"
	hostBundleDir  = "internal/hostbundle/"
	tuningChoreLit = "chore=tuning"
)

// tuningViolations returns why src, read from path, names tuning outside the
// places allowed to: an identifier containing "tuning", an import of a package
// called tuning, or -- under settle -- a `chore=tuning` string constant.
// Parsing rather than line-matching keeps strings and comments (env names, the
// "agent-tuning-finding" label, historical migration SQL) out of scope.
func tuningViolations(filePath string, src []byte) []string {
	p := filepath.ToSlash(filePath)
	if strings.HasPrefix(p, tuningPkgDir) || strings.HasPrefix(p, hostBundleDir) {
		return nil
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filePath, src, parser.ParseComments)
	if err != nil {
		return []string{fmt.Sprintf("%s: cannot parse: %v", filePath, err)}
	}
	// The header alone would let a hand-written file opt out; regen names
	// every file it writes *_gen.go.
	if ast.IsGenerated(file) && strings.HasSuffix(p, "_gen.go") {
		return nil
	}
	inSettle := strings.HasPrefix(p, settleDir)
	var out []string
	add := func(pos token.Pos, why string) {
		out = append(out, fmt.Sprintf("%s:%d: %s", filePath, fset.Position(pos).Line, why))
	}
	const allowed = " -- only internal/tuning, internal/hostbundle and generated code may"
	ast.Inspect(file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.Ident:
			if strings.Contains(strings.ToLower(n.Name), "tuning") {
				add(n.Pos(), "identifier "+n.Name+" names tuning"+allowed)
			}
		case *ast.ImportSpec:
			if ip, err := strconv.Unquote(n.Path.Value); err == nil && path.Base(ip) == "tuning" {
				add(n.Pos(), "imports "+ip+allowed)
			}
		case *ast.BasicLit, *ast.BinaryExpr:
			if s, ok := stringConst(n.(ast.Expr)); inSettle && ok && strings.Contains(s, tuningChoreLit) {
				add(n.Pos(), "settle spells "+tuningChoreLit+" -- read the row's axis instead")
				return false
			}
		}
		return true
	})
	return out
}

// stringConst folds a string literal, or a `+` chain of them, to its value, so
// `"chore=" + "tuning"` cannot slip past the settle check.
func stringConst(e ast.Expr) (string, bool) {
	switch e := e.(type) {
	case *ast.BasicLit:
		if e.Kind != token.STRING {
			return "", false
		}
		s, err := strconv.Unquote(e.Value)
		return s, err == nil
	case *ast.BinaryExpr:
		if e.Op != token.ADD {
			return "", false
		}
		x, xok := stringConst(e.X)
		y, yok := stringConst(e.Y)
		return x + y, xok && yok
	case *ast.ParenExpr:
		return stringConst(e.X)
	}
	return "", false
}

// TestTuningNamedOnlyByItsPackageBundleAndGeneratedCode pins the ADR 0070
// registry boundary (issue #5701): non-test code names tuning only from
// internal/tuning, the host bundle internal/hostbundle, and generated files,
// so the core stays blind to which Digests exist.
func TestTuningNamedOnlyByItsPackageBundleAndGeneratedCode(t *testing.T) {
	settleFiles, tuningFiles := 0, 0
	err := filepath.WalkDir(".", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if name := d.Name(); p != "." && (name == "testdata" || strings.HasPrefix(name, ".")) {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
			return nil
		}
		slash := filepath.ToSlash(p)
		if strings.HasPrefix(slash, settleDir) {
			settleFiles++
		}
		if strings.HasPrefix(slash, tuningPkgDir) {
			tuningFiles++
		}
		raw, readErr := os.ReadFile(p)
		if readErr != nil {
			return readErr
		}
		for _, v := range tuningViolations(p, raw) {
			t.Error(v)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk .: %v", err)
	}
	if settleFiles == 0 || tuningFiles == 0 {
		t.Fatalf("saw %d files under %s and %d under %s: the guard is matching the wrong path", settleFiles, settleDir, tuningFiles, tuningPkgDir)
	}
}

// TestTuningGuardPlanted plants sources at core and exempt paths and pins
// which ones the guard flags.
func TestTuningGuardPlanted(t *testing.T) {
	const use = "package x\n\nvar _ = tuning.Strategy\n\ntype tuningSnapshot struct{}\n"
	for _, tc := range []struct {
		name, path, src string
		want            int
	}{
		{"core use", "internal/dispatch/x.go", use, 2},
		{"tuning package", tuningPkgDir + "x.go", use, 0},
		{"host bundle", hostBundleDir + "x.go", use, 0},
		{"generated", "internal/dispatch/x_gen.go", "// Code generated by nix/regen.nix from rows. DO NOT EDIT.\n\n" + use, 0},
		{"chore literal in settle", settleDir + "x.go", "package x\n\nvar _ = \"chore=tuning\"\n", 1},
		{"split chore literal in settle", settleDir + "x.go", "package x\n\nvar _ = \"chore=\" + (\"tun\" + \"ing\")\n", 1},
		{"generated header without the _gen.go name", "internal/dispatch/x.go", "// Code generated by hand. DO NOT EDIT.\n\n" + use, 2},
		{"chore literal outside settle", "internal/dispatch/x.go", "package x\n\nvar _ = \"chore=tuning\"\n", 0},
		{"comment only", "internal/dispatch/x.go", "package x\n\n// tuning is out of scope here.\nvar _ = 1\n", 0},
		{"non-settle string", "internal/dispatch/x.go", "package x\n\nvar _ = \"agent-tuning-finding\"\n", 0},
		{"settle string without the chore term", settleDir + "x.go", "package x\n\nvar _ = \"agent-tuning-finding\"\n", 0},
		{"blank import", "internal/dispatch/x.go", "package x\n\nimport _ \"spindrift.dev/launcher/internal/tuning\"\n", 1},
		{"import alias", "internal/dispatch/x.go", "package x\n\nimport t \"spindrift.dev/launcher/internal/tuning\"\n\nvar _ = t.X\n", 1},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got := tuningViolations(tc.path, []byte(tc.src))
			if len(got) != tc.want {
				t.Errorf("%s: %d violations %q, want %d", tc.path, len(got), got, tc.want)
			}
			if tc.want > 0 && !slices.ContainsFunc(got, func(s string) bool { return strings.HasPrefix(s, tc.path+":") }) {
				t.Errorf("violations %q do not name %s with a line", got, tc.path)
			}
		})
	}
}
